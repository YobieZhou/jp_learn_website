export const shadowingLessons = catalog.map(([id, sourcePage, level, topic, title, titleZh]) => {
  const content = prepared[id];
  const notes = content ?? shadowingNotes[id];
  const transcript = content?.sentences ?? (extractedTranscripts[id]?.map((jp) => [jp, ""]) ?? []);
  const levelProfile = levelProfiles[id] ?? {
    label: level,
    filters: [level],
    origin: "source",
    originLabel: "资料标注",
    note: `原资料明确标注为 ${level}。`
  };
  return {
    id,
    sourcePage,
    level,
    levelLabel: levelProfile.label,
    levelFilters: levelProfile.filters,
    levelOrigin: levelProfile.origin,
    levelOriginLabel: levelProfile.originLabel,
    levelNote: levelProfile.note,
    topic,
    title,
    titleZh,
    ready: transcript.length > 0,
    sentences: transcript.map(([jp, zh], index) => ({
      jp,
      zh,
      furigana: shadowingReadings[id]?.[index] ?? [jp],
      paragraph: Math.floor(index / 3),
      audio: `assets/audio/shadowing/lesson-${String(id).padStart(2, "0")}/${String(index + 1).padStart(2, "0")}.wav`
    })),
    vocabulary: notes?.vocabulary.map(([word, reading, meaning]) => ({ word, reading, meaning })) ?? [],
    grammar: notes?.grammar.map(([pattern, note]) => ({ pattern, note })) ?? []
  };
});

const trackedLevels = ["N3", "N4", "N5"];
const exactLevelCounts = Object.fromEntries(trackedLevels.map((level) => [
  level,
  shadowingLessons.filter((lesson) => lesson.levelLabel === level).length
]));
const filterLevelCounts = Object.fromEntries(trackedLevels.map((level) => [
  level,
  shadowingLessons.filter((lesson) => lesson.levelFilters.includes(level)).length
]));

export const shadowingCatalogSummary = Object.freeze({
  total: shadowingLessons.length,
  ready: shadowingLessons.filter((lesson) => lesson.ready).length,
  sourceMarked: shadowingLessons.filter((lesson) => lesson.levelOrigin === "source").length,
  assessed: shadowingLessons.filter((lesson) => lesson.levelOrigin === "assessed").length,
  transition: shadowingLessons.filter((lesson) => lesson.levelFilters.length > 1).length,
  levels: Object.freeze(exactLevelCounts),
  filters: Object.freeze(filterLevelCounts)
});
